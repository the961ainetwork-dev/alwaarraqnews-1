const DISPATCHES_STORAGE_KEY = 'alwarraq_intelligence_dispatches';

export function getStoredDispatches(): IntelligenceDispatch[] {
  try {
    const raw = localStorage.getItem(DISPATCHES_STORAGE_KEY);
    if (raw) {
      const parsed = JSON.parse(raw);
      if (Array.isArray(parsed) && parsed.length > 0) {
        return parsed;
      }
    }
  } catch (err) {
    console.error('Failed to parse stored dispatches:', err);
  }
  return INITIAL_INTELLIGENCE_DISPATCHES;
}

export function saveStoredDispatches(dispatches: IntelligenceDispatch[]): void {
  try {
    localStorage.setItem(DISPATCHES_STORAGE_KEY, JSON.stringify(dispatches));
  } catch (err) {
    console.error('Failed to save dispatches to storage:', err);
  }
}

export function saveNewOrUpdatedDispatch(dispatch: IntelligenceDispatch): IntelligenceDispatch[] {
  const current = getStoredDispatches();
  const existingIndex = current.findIndex(d => d.id === dispatch.id || d.issueNumber === dispatch.issueNumber);
  let updated: IntelligenceDispatch[];
  if (existingIndex >= 0) {
    updated = [...current];
    updated[existingIndex] = { ...dispatch, timestamp: Date.now() };
  } else {
    updated = [dispatch, ...current];
  }
  saveStoredDispatches(updated);
  return updated;
}
